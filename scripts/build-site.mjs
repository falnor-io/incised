#!/usr/bin/env node
// Builds what the docs site needs from the repo, so the docs cannot drift from the components:
//   site/src/generated/specimens.tsx   every demo specimen, cut out of demo/main.tsx (one source for demo and docs)
//   site/content/docs/components/*     one page per component: live preview, install, example, props
// Run from the repo root or from site/ (npm run generate there).
import { mkdirSync, readFileSync, writeFileSync, rmSync, existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { execFileSync } from 'node:child_process'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const site = join(root, 'site')
const read = (p) => readFileSync(join(root, p), 'utf8')
const kebab = (n) => n.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase()

// Props and descriptions, read from the TypeScript types.
execFileSync('node', [join(root, 'scripts/build-docs.mjs')], { cwd: root, stdio: 'ignore' })
const propsByName = JSON.parse(read('docs/components.json'))
const registry = JSON.parse(read('registry.json')).items

// ---- specimens, cut out of the demo
const main = read('demo/main.tsx')
const head = main.slice(0, main.indexOf('function Spec('))
const mid = main.slice(main.indexOf('const runColumns'), main.indexOf('function App()'))
const stateBlock = main.slice(main.indexOf('  const [good'), main.indexOf('  return (\n    <main>'))
const imports = head
  .replace('const library = buildOrluneLibrary()', '')
  .split('\n')
  .filter((l) => !l.startsWith("import '"))
  .join('\n')
  .replace(/'\.\.\/src\/index\.js'/g, "'orlune'")
  .replace(/'\.\.\/src\/openui\/index\.js'/g, "'orlune/openui'")
  .replace(/'\.\.\/src\/verify\/index\.js'/g, "'orlune/verify'")
  .replace(/'\.\/sample-record\.json'/g, "'@demo/sample-record.json'")
  .replace(/'\.\/data\.js'/g, "'@demo/data'")
  .replace(/'\.\.\/src\/components\/trace\.js'/g, "'orlune'")

const specRe = /<Spec name="([^"]+)" kind="([^"]+)" note="([^"]*)">\n([\s\S]*?)\n\s*<\/Spec>/g
const specs = []
for (const m of main.matchAll(specRe)) specs.push({ name: m[1], kind: m[2], note: m[3], body: m[4].replace(/library=\{library\}/g, 'library={getLibrary()}') })

const dedent = (text) => {
  const lines = text.split('\n')
  const indent = Math.min(...lines.filter((l) => l.trim()).map((l) => l.match(/^ */)[0].length))
  return lines.map((l) => l.slice(indent)).join('\n')
}

mkdirSync(join(site, 'src/generated'), { recursive: true })
writeFileSync(
  join(site, 'src/generated/specimens.tsx'),
  `// Generated by scripts/build-site.mjs from demo/main.tsx. Do not edit.
${imports}
${mid}
// Created on first use, not at import: Workers refuse random values in global scope and createLibrary makes an id.
let libraryCache: ReturnType<typeof buildOrluneLibrary> | undefined
const getLibrary = () => (libraryCache ??= buildOrluneLibrary())
export type SpecimenData = { good: VerifyResult | null; bad: VerifyResult | null; unknown: VerifyResult | null; queue: QueueItem[] | null }

export function useSpecimenData(): SpecimenData {
${stateBlock}  return { good, bad, unknown, queue }
}

export const specimens: Record<string, (d: SpecimenData) => ReactNode> = {
${specs.map((s) => `  ${JSON.stringify(s.name)}: ({ good, bad, unknown, queue }) => (\n    <>\n${s.body}\n    </>\n  ),`).join('\n')}
}

export const specimenMeta: Record<string, { kind: string; note: string; code: string }> = {
${specs.map((s) => `  ${JSON.stringify(s.name)}: { kind: ${JSON.stringify(s.kind)}, note: ${JSON.stringify(s.note)}, code: ${JSON.stringify(dedent(s.body))} },`).join('\n')}
}
`
)

// ---- one page per component
const dir = join(site, 'content/docs/components')
rmSync(dir, { recursive: true, force: true })
mkdirSync(dir, { recursive: true })
const byFile = Object.fromEntries(specs.map((s) => [s.name, s]))
const groups = { Workflow: [], Record: [], Complex: [], Judgement: [], Workspace: [] }
const esc = (s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ')
for (const item of registry) {
  if (item.type !== 'registry:component' || !item.files?.[0]) continue
  const comp = item.files[0].path.match(/components\/(\w+)\.tsx$/)?.[1]
  const spec = comp && byFile[comp]
  if (!spec || !propsByName[comp]) continue
  const info = propsByName[comp]
  const rows = info.props.map((p) => `| \`${p.name}\` | \`${esc(p.type).slice(0, 110)}\` | ${p.required ? 'yes' : 'no'} | ${esc(p.notes)} |`)
  groups[spec.kind]?.push(item.name)
  writeFileSync(
    join(dir, `${item.name}.mdx`),
    `---
title: ${item.title}
description: ${JSON.stringify(item.description)}
---

<ComponentPreview name="${comp}" />

${spec.note}

## Installation

\`\`\`bash
npx shadcn@latest add @orlune/${item.name}
\`\`\`

Or import it from the package: \`import { ${comp} } from 'orlune'\`.

## Example

The data below is the data in the preview above.

\`\`\`tsx
${dedent(spec.body)}
\`\`\`

## Props

${rows.length ? `| Prop | Type | Required | Notes |\n| --- | --- | --- | --- |\n${rows.join('\n')}` : 'No props.'}

Pass \`className\` to add your own class.
`
  )
}
const order = ['Workflow', 'Record', 'Complex', 'Judgement', 'Workspace']
writeFileSync(
  join(dir, 'meta.json'),
  JSON.stringify({ title: 'Components', pages: ['index', ...order.flatMap((g) => [`---${g}---`, ...groups[g]])] }, null, 2) + '\n'
)
writeFileSync(
  join(dir, 'index.mdx'),
  `---
title: Overview
description: ${JSON.stringify(`${order.reduce((n, g) => n + groups[g].length, 0)} components in three sets. Each takes plain data and computes everything derived itself.`)}
---

${order
  .map((g) => `## ${g}\n\n<Cards>\n${groups[g].map((n) => `  <Card title="${registry.find((i) => i.name === n).title}" href="/docs/components/${n}">${registry.find((i) => i.name === n).description}</Card>`).join('\n')}\n</Cards>`)
  .join('\n\n')}
`
)
console.log(`site: ${specs.length} specimens, ${order.reduce((n, g) => n + groups[g].length, 0)} component pages`)
