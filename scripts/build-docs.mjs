#!/usr/bin/env node
// Writes docs/COMPONENTS.md: one section per exported component, with what it is for and a table of its props,
// read from the TypeScript types and the comments in src/. Run with: npm run docs
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import ts from 'typescript'

const root = new URL('..', import.meta.url).pathname
const cfgPath = join(root, 'tsconfig.json')
const cfg = ts.readConfigFile(cfgPath, ts.sys.readFile)
const parsed = ts.parseJsonConfigFileContent(cfg.config, ts.sys, root)
const program = ts.createProgram({ rootNames: [join(root, 'src/index.ts')], options: parsed.options })
const checker = program.getTypeChecker()
const index = program.getSourceFile(join(root, 'src/index.ts'))
const mod = checker.getSymbolAtLocation(index)
const exports = checker.getExportsOfModule(mod)

const sets = JSON.parse(readFileSync(join(root, 'registry.json'), 'utf8')).items
const descOf = Object.fromEntries(sets.map((i) => [i.name, i.description]))
const kebab = (n) => n.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase()

const short = (s) => s.replace(/\s+/g, ' ').replace(/\|/g, '\\|').slice(0, 90) + (s.length > 90 ? '...' : '')
const out = []
const components = exports.filter((s) => /^[A-Z]/.test(s.name))
for (const sym of components) {
  const real = sym.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(sym) : sym
  const decl = real.declarations?.[0]
  if (!decl || !ts.isFunctionDeclaration(decl) || !decl.parameters[0]) continue
  const doc = ts.displayPartsToString(real.getDocumentationComment(checker)).replace(/\s+/g, ' ').trim()
  const type = checker.getTypeAtLocation(decl.parameters[0])
  const props = checker.getPropertiesOfType(type).filter((p) => p.name !== 'className')
  const rows = props.map((p) => {
    const t = checker.getTypeOfSymbolAtLocation(p, decl)
    const optional = (p.flags & ts.SymbolFlags.Optional) !== 0
    const d = ts.displayPartsToString(p.getDocumentationComment(checker)).replace(/\s+/g, ' ').trim()
    return `| \`${p.name}\` | \`${short(checker.typeToString(t, decl, ts.TypeFormatFlags.NoTruncation))}\` | ${optional ? 'no' : 'yes'} | ${short(d)} |`
  })
  out.push(`## ${real.name}\n\n${doc || descOf[kebab(real.name)] || ''}\n\n${rows.length ? '| Prop | Type | Required | Notes |\n| --- | --- | --- | --- |\n' + rows.join('\n') : 'No props.'}\n\nInstall: \`npx shadcn@latest add falnor-io/orlune/${kebab(real.name)}\`\n`)
}
const head = `# Components\n\nEvery component is exported from \`orlune\`. Each takes plain data. Anything derived (shares, totals, intervals) is computed inside the component, and verification state comes only from \`verifyRecord\`. Pass \`className\` to any of them.\n\nGenerated by \`npm run docs\` from the types in \`src/\`. Do not edit by hand.\n\n`
writeFileSync(join(root, 'docs/COMPONENTS.md'), head + out.join('\n'))
// The same facts as data, for the docs site.
const json = {}
for (const sym of components) {
  const real = sym.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(sym) : sym
  const decl = real.declarations?.[0]
  if (!decl || !ts.isFunctionDeclaration(decl) || !decl.parameters[0]) continue
  const doc = ts.displayPartsToString(real.getDocumentationComment(checker)).replace(/\s+/g, ' ').trim()
  const type = checker.getTypeAtLocation(decl.parameters[0])
  json[real.name] = {
    doc: doc || descOf[kebab(real.name)] || '',
    props: checker.getPropertiesOfType(type).filter((p) => p.name !== 'className').map((p) => ({
      name: p.name,
      type: checker.typeToString(checker.getTypeOfSymbolAtLocation(p, decl), decl, ts.TypeFormatFlags.NoTruncation),
      required: (p.flags & ts.SymbolFlags.Optional) === 0,
      notes: ts.displayPartsToString(p.getDocumentationComment(checker)).replace(/\s+/g, ' ').trim(),
    })),
  }
}
writeFileSync(join(root, 'docs/components.json'), JSON.stringify(json, null, 1) + '\n')
console.log(`docs: ${out.length} components -> docs/COMPONENTS.md`)
